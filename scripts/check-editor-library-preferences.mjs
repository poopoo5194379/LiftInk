import assert from 'node:assert/strict'
import { mkdtemp, readFile, readdir, rm } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { _electron as electron, expect } from '@playwright/test'
import JSZip from 'jszip'

const root = await mkdtemp(join(tmpdir(), 'liftink-library-preferences-'))
const executablePath = process.env.LIFTINK_TEST_PACKAGED_EXE
const app = await electron.launch({ executablePath, args: executablePath ? [] : ['.'], env: { ...process.env, LIFTINK_TEST_DATA_DIR: root } })

try {
  const page = await app.firstWindow()
  page.setDefaultTimeout(8000)
  const button = (name) => page.getByRole('button', { name, exact: true })
  assert.equal(await app.evaluate(({ app }) => app.getName()), 'LiftInk')
  await expect(page).toHaveTitle('LiftInk')
  const window = await app.browserWindow(page)
  await window.evaluate((window) => window.setContentSize(1200, 700))
  const entry = await button('查看全部日程').boundingBox()
  const add = await page.locator('.schedule-actions').getByRole('button', { name: '新增日程', exact: true }).boundingBox()
  assert(entry.x > add.x && Math.abs(entry.y - add.y) < 1)
  await button('查看全部日程').click()
  await expect(page.getByRole('region', { name: '周历' })).toBeVisible()
  await button('新增日程').click()
  await page.getByPlaceholder('输入日程内容').fill('设计计划')
  await button('添加日程').click()
  await button('周视图').click()
  await expect(page.locator('.agenda-range-day')).toHaveCount(7)
  const columns = await page.locator('.agenda-range-day').evaluateAll((days) => days.map((day) => {
    const { x, y } = day.getBoundingClientRect()
    return { x, y }
  }))
  assert(columns.every((day, index) => day.y === columns[0].y && (!index || day.x > columns[index - 1].x)))
  await expect(page.locator('.agenda-date-list button')).toHaveCount(7)
  await button('月视图').click()
  await expect(page.locator('.agenda-month-grid')).toContainText('设计计划')
  await expect(page.locator('.agenda-month-grid > strong')).toHaveCount(7)
  await button('返回首页').click()
  await expect(page.locator('.calendar-grid .agenda-date-dot')).toHaveCount(1)

  await button('设置').click()
  await expect(page.getByRole('navigation', { name: '设置分类' }).getByRole('button')).toHaveCount(9)
  await page.getByRole('button', { name: /书写体验/ }).click()
  const settings = page.getByRole('region', { name: '设置页面' })
  const scrollbar = await settings.evaluate((element) => {
    const { right, top } = element.getBoundingClientRect()
    return { x: right - (element.offsetWidth - element.clientWidth) / 2, y: top + 28 }
  })
  await page.mouse.move(scrollbar.x, scrollbar.y)
  await page.mouse.down()
  await page.mouse.move(scrollbar.x, scrollbar.y + 140, { steps: 7 })
  await page.mouse.up()
  await expect.poll(() => settings.evaluate((element) => element.scrollTop)).toBeGreaterThan(0)
  await settings.hover({ position: { x: 60, y: 150 } })
  await page.mouse.wheel(0, -3000)
  await expect.poll(() => settings.evaluate((element) => element.scrollTop)).toBe(0)
  await window.evaluate((window) => window.setContentSize(1440, 900))
  await page.getByRole('button', { name: /画布与笔记/ }).click()
  await page.getByLabel('默认纸张', { exact: true }).selectOption('a5')
  await page.getByLabel('默认纸张背景').selectOption('dots')
  await page.getByLabel('默认纸张颜色').selectOption('cream')
  await page.getByRole('button', { name: /书写体验/ }).click()
  await expect(page.getByRole('img', { name: '书写测试画布' })).toBeVisible()
  await button('返回首页').click()
  await page.getByRole('button', { name: /^新建笔记/ }).click()
  await page.getByLabel('笔记标题').fill('我们自己研究 分析 包括')
  await button('编辑笔记标签').click()
  for (const tag of ['设计', '项目']) {
    await page.getByLabel('新标签名称').fill(tag)
    await button('添加').click()
  }
  await expect(page.getByLabel('设计', { exact: true })).toBeChecked()
  await expect(page.getByLabel('项目', { exact: true })).toBeChecked()
  await page.keyboard.press('Escape')
  const canvas = page.getByRole('img', { name: '笔记画布' }).first()
  await canvas.evaluate((element) => Promise.all(element.closest('main').getAnimations().map((animation) => animation.finished)))
  await expect(canvas).toHaveAttribute('viewBox', '0 0 559 794')
  const cdp = await page.context().newCDPSession(page)
  const draw = async (x, y, dx, dy) => {
    const bounds = await canvas.boundingBox()
    const pointer = (type, atX, atY) => cdp.send('Input.dispatchMouseEvent', {
      type, x: bounds.x + atX, y: bounds.y + atY, pointerType: 'pen', force: type === 'mouseReleased' ? 0 : 0.5,
      button: type === 'mouseMoved' ? 'none' : 'left', buttons: type === 'mouseReleased' ? 0 : 1
    })
    await pointer('mousePressed', x, y)
    await pointer('mouseMoved', x + dx / 2, y + dy / 2)
    await pointer('mouseMoved', x + dx, y + dy)
    await pointer('mouseReleased', x + dx, y + dy)
  }
  await button('形状').click()
  await draw(110, 120, 100, 65)
  await button('遮挡胶带').click()
  await draw(110, 225, 100, 45)
  await expect(canvas.locator('[data-tape-id]')).toHaveCount(1)
  await button('选择').click()
  await canvas.click({ position: { x: 140, y: 145 } })
  await expect(canvas.getByLabel('拖动调整形状大小')).toBeVisible()
  await page.getByLabel('形状颜色').fill('#4058a5')
  await canvas.locator('[data-tape-id]').click()
  await button('揭开遮挡胶带').click()
  await expect(button('盖回遮挡胶带')).toBeVisible()
  await button('删除选区').click()
  await expect(canvas.locator('[data-tape-id]')).toHaveCount(0)
  await page.keyboard.press('Control+z')
  await expect(canvas.locator('[data-tape-id]')).toHaveCount(1)
  await button('展开页面缩略图').click()
  await button('新增页面').click()

  const pdfPath = join(root, 'source.pdf')
  await app.evaluate(({ dialog }, path) => {
    dialog.showSaveDialog = async () => ({ canceled: false, filePath: path })
  }, pdfPath)
  await page.evaluate(() => window.liftInk.exportMarkdownPdf('Source', '<h1>Selectable PDF text</h1><p>Study and analysis</p>'))
  await page.locator('input[accept="application/pdf,.pdf"]').setInputFiles(pdfPath)
  const importDialog = page.getByRole('dialog', { name: '插入 PDF' })
  await expect(importDialog.getByRole('option', { name: '插入最开始' })).toBeAttached()
  await expect(importDialog.getByRole('option', { name: '插入最末' })).toBeAttached()
  await importDialog.getByLabel('插入位置').selectOption({ label: '在第 2 页前插入' })
  await importDialog.getByRole('button', { name: '插入 PDF' }).click()
  await expect(button('选择 PDF 原文')).toBeVisible()
  await button('选择 PDF 原文').click()
  const pdfText = page.locator('.pdf-selectable-text span').filter({ hasText: 'Selectable PDF text' }).first()
  await expect(pdfText).toBeAttached()
  await pdfText.scrollIntoViewIfNeeded()
  const bounds = await pdfText.boundingBox()
  assert(bounds && bounds.width > 20 && bounds.height > 5)
  await page.mouse.move(bounds.x + 1, bounds.y + bounds.height / 2)
  await page.mouse.down()
  await page.mouse.move(bounds.x + bounds.width - 1, bounds.y + bounds.height / 2, { steps: 12 })
  await page.mouse.up()
  const selection = await page.evaluate(({ x, y, height }) => ({
    text: window.getSelection().toString(), hit: document.elementFromPoint(x + 2, y + height / 2)?.outerHTML.slice(0, 200)
  }), bounds)
  assert.match(selection.text, /Select/, JSON.stringify(selection))
  await button('选择 PDF 原文').click()
  await page.keyboard.press('Control+s')
  const read = () => page.evaluate(async () => {
    const { value: notes } = await window.liftInk.loadNoteIndex()
    const note = notes.find((item) => item.title.includes('研究'))
    const { value: document } = await window.liftInk.loadDocument(note.id)
    return { note, pages: document.pages }
  })
  await expect.poll(async () => (await read()).pages[1]?.sourcePageNumber).toBe(1)
  const { note, pages } = await read()
  assert.deepEqual(note.tags, ['设计', '项目'])
  assert.equal(pages[0].paper, 'dots')
  assert.equal(pages[0].paperColor, 'cream')
  assert.equal(pages[0].elements.find((item) => item.kind === 'shape').color, '#4058a5')
  assert.equal(pages[0].elements.find((item) => item.kind === 'tape').revealed, true)
  await button('返回上一页').click()
  const cloud = page.locator('.word-cloud')
  await expect(cloud.getByRole('button', { name: '研究', exact: true })).toBeVisible()
  assert(!(await cloud.getByRole('button').allTextContents()).some((word) => ['我们', '自己', '包括'].includes(word)))
  await cloud.getByRole('button', { name: '研究', exact: true }).click({ button: 'right' })
  const blockDialog = page.getByRole('dialog', { name: '屏蔽关键词' })
  await expect(blockDialog).toContainText('研究')
  await blockDialog.getByRole('button', { name: '取消' }).click()
  await expect(cloud.getByRole('button', { name: '研究', exact: true })).toBeVisible()
  await cloud.getByRole('button', { name: '研究', exact: true }).click({ button: 'right' })
  await blockDialog.getByRole('button', { name: '不再显示此词' }).click()
  await expect(cloud.getByRole('button', { name: '研究', exact: true })).toHaveCount(0)
  await page.reload()
  await expect(cloud.getByRole('button', { name: '分析', exact: true })).toBeVisible()
  await expect(cloud.getByRole('button', { name: '研究', exact: true })).toHaveCount(0)

  await button('设置').click()
  await page.getByRole('button', { name: /文件与备份/ }).click()
  await app.evaluate(({ dialog }, backupPath) => {
    dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [backupPath] })
  }, root)
  await button('选择备份目录').click()
  await expect(page.locator('.storage-path')).toHaveCount(2)
  await button('导出 .liftink').click()
  await expect.poll(async () => (await readdir(root)).filter((file) => file.endsWith('.liftink')).length).toBe(1)
  const backups = await readdir(root)
  const backupPath = join(root, backups.find((file) => file.endsWith('.liftink')))
  const backup = await JSZip.loadAsync(await readFile(backupPath))
  const manifest = JSON.parse(await backup.file('manifest.json').async('string'))
  assert.deepEqual(manifest.settings.blockedKeywords, ['研究'])
  assert(backup.file(`assets/${pages[1].sourcePdfId}`))
  await page.locator('input[accept=".liftink"]').setInputFiles(backupPath)
  await expect(page.getByText(/已恢复 1 篇笔记/)).toBeVisible()
  const restored = await page.evaluate(async () => (await window.liftInk.loadNoteIndex()).value.filter((item) => item.title.includes('研究')))
  assert.equal(restored.length, 2)
  assert.notEqual(restored[0].id, restored[1].id)
  await page.getByRole('button', { name: /^通用/ }).click()
  const wordList = page.getByRole('region', { name: '思绪拾光屏蔽词' })
  await wordList.getByRole('button', { name: '恢复显示 研究' }).click()
  await expect(wordList).toContainText('暂无屏蔽词')
  await button('返回首页').click()
  await expect(cloud.getByRole('button', { name: '研究', exact: true })).toBeVisible()
  await cdp.detach()
  console.log('Agenda, note tags, shapes and tape, PDF insertion and native selection, paper defaults, blocked keywords and backup passed')
} finally {
  await app.close()
  await rm(root, { recursive: true, force: true })
}
