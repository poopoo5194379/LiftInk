import { strict as assert } from 'node:assert'
import { mkdtemp, readFile, readdir, rm, stat } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { _electron as electron } from '@playwright/test'
import { PDFDocument } from 'pdf-lib'
import JSZip from 'jszip'

const root = await mkdtemp(join(tmpdir(), 'liftink-p1-p3-'))
const exportDir = await mkdtemp(join(tmpdir(), 'liftink-exports-'))
const app = await electron.launch({ args: ['.'], env: { ...process.env, LIFTINK_TEST_DATA_DIR: root, LIFTINK_TEST_EXPORT_DIR: exportDir } })
const page = await app.firstWindow()
page.on('pageerror', (error) => console.error('renderer:', error.message))
// eslint-disable-next-line @typescript-eslint/explicit-function-return-type
async function waitDocument(id, predicate, timeout = 20000) {
  const start = Date.now()
  while (Date.now() - start < timeout) {
    const result = (await page.evaluate((noteId) => window.liftInk.loadDocument(noteId), id)).value
    if (result && predicate(result)) return result
    await page.waitForTimeout(150)
  }
  throw new Error(`保存等待超时：${await page.locator('.editor-save-state').textContent()}`)
}
try {
  await (await app.browserWindow(page)).evaluate((window) => window.setContentSize(1440, 900))
  await app.evaluate(({ dialog }, folder) => {
    dialog.showSaveDialog = async (_owner, options) => ({ canceled: false, filePath: `${folder}\\${options.defaultPath.split(/[\\/]/).at(-1)}` })
  }, exportDir)
  await page.getByRole('button', { name: '新建笔记' }).click()
  await page.getByRole('region', { name: '笔记页面' }).waitFor()
  await page.getByLabel('笔记标题').fill('P1-P3 主笔记')
  await page.keyboard.press('Control+s')
  await page.getByText('已保存', { exact: true }).waitFor()
  const noteId = await page.evaluate(async () => (await window.liftInk.loadNoteIndex()).value.find((note) => note.originalTitle.startsWith('new-')).id)
  const canvas = page.getByLabel('笔记画布').first()
  const box = await canvas.boundingBox()
  assert(box)
  await page.mouse.move(box.x + 140, box.y + 160)
  await page.mouse.down()
  await page.mouse.move(box.x + 300, box.y + 200, { steps: 20 })
  await page.mouse.up()
  await page.getByRole('button', { name: '展开页面缩略图' }).click()
  await page.getByRole('button', { name: '新增页面' }).click()
  assert.equal(await page.getByLabel('笔记画布').count(), 2)
  await page.getByRole('button', { name: '第 2 页上移' }).click()
  let saved = (await page.evaluate((id) => window.liftInk.loadDocument(id), noteId)).value
  assert.equal(saved.pages.length, 2)
  assert.equal(saved.pages[0].elements.length, 0)
  await page.getByRole('button', { name: '第 1 页下移' }).click()
  await page.getByRole('button', { name: '图层', exact: true }).click()
  await page.getByRole('button', { name: '新增图层' }).click()
  await page.getByLabel('图层名称').fill('复习层')
  await page.getByRole('button', { name: '确定' }).click()
  assert(await page.getByRole('button', { name: '复习层锁定' }).isVisible(), await page.locator('.editor-layer-list').innerText())
  await page.getByRole('button', { name: '复习层锁定' }).click()
  await page.getByRole('button', { name: '钢笔', exact: true }).click()
  const activeCanvas = page.getByLabel('笔记画布').nth(1)
  await activeCanvas.scrollIntoViewIfNeeded()
  const activeBox = await activeCanvas.boundingBox()
  await page.mouse.click(activeBox.x + 100, activeBox.y + 100)
  saved = (await page.evaluate((id) => window.liftInk.loadDocument(id), noteId)).value
  assert.equal(saved.pages[1].elements.length, 0, '锁定图层阻止书写')
  await page.getByRole('button', { name: '复习层解锁' }).click()
  await page.getByRole('button', { name: '形状' }).click()
  await page.mouse.move(activeBox.x + 120, activeBox.y + 320)
  await page.mouse.down()
  await page.mouse.move(activeBox.x + 230, activeBox.y + 390)
  await page.mouse.up()
  await page.getByRole('button', { name: '遮挡胶带' }).click()
  await page.mouse.move(activeBox.x + 250, activeBox.y + 420)
  await page.mouse.down()
  await page.mouse.move(activeBox.x + 370, activeBox.y + 455)
  await page.mouse.up()
  saved = (await page.evaluate((id) => window.liftInk.loadDocument(id), noteId)).value
  assert(saved.pages[1].elements.some((element) => element.kind === 'shape'), JSON.stringify(saved.pages.map((entry) => entry.elements.map((element) => element.kind))))
  assert(saved.pages[1].elements.some((element) => element.kind === 'tape'))
  await page.mouse.click(activeBox.x + 310, activeBox.y + 440)
  await waitDocument(noteId, (value) => value.pages[1].elements.some((element) => element.kind === 'tape' && element.revealed))
  const originalShape = saved.pages[1].elements.find((element) => element.kind === 'shape')
  await page.getByRole('button', { name: '选择', exact: true }).click()
  await activeCanvas.locator('rect').first().scrollIntoViewIfNeeded()
  const selectBox = await activeCanvas.boundingBox()
  // eslint-disable-next-line @typescript-eslint/explicit-function-return-type
  const at = (x, y) => ({ x: selectBox.x + x * selectBox.width / 750, y: selectBox.y + y * selectBox.height / 980 })
  const left = originalShape.x - 18, top = originalShape.y - 18
  const right = originalShape.x + originalShape.width + 18, bottom = originalShape.y + originalShape.height + 18
  let cursor = at(left, top)
  await page.mouse.move(cursor.x, cursor.y)
  await page.mouse.down()
  for (const [x, y] of [[right, top], [right, bottom], [left, bottom], [left, top]]) { cursor = at(x, y); await page.mouse.move(cursor.x, cursor.y, { steps: 4 }) }
  await page.mouse.up()
  assert(await page.getByRole('button', { name: '复制选区' }).isVisible(), '套索应选中形状')
  cursor = at(originalShape.x + originalShape.width / 2, originalShape.y + originalShape.height / 2)
  await page.mouse.move(cursor.x, cursor.y)
  await page.mouse.down()
  await page.mouse.move(cursor.x + 40, cursor.y + 20, { steps: 4 })
  await page.mouse.up()
  saved = await waitDocument(noteId, (value) => value.pages[1].elements.find((element) => element.id === originalShape.id)?.x > originalShape.x)
  await page.getByRole('button', { name: '复制选区' }).click()
  saved = await waitDocument(noteId, (value) => value.pages[1].elements.filter((element) => element.kind === 'shape').length === 2)
  await page.getByRole('button', { name: '放大选区' }).click()
  await waitDocument(noteId, (value) => value.pages[1].elements.filter((element) => element.kind === 'shape').some((element) => element.width > originalShape.width))
  await page.getByRole('button', { name: '形状' }).click()
  await page.getByLabel('形状类型').selectOption('ellipse')
  await activeCanvas.locator('rect').first().scrollIntoViewIfNeeded()
  const shapeBox = await activeCanvas.boundingBox()
  await page.mouse.move(shapeBox.x + 400, shapeBox.y + 390)
  await page.mouse.down()
  await page.mouse.move(shapeBox.x + 460, shapeBox.y + 430)
  await page.mouse.up()
  await waitDocument(noteId, (value) => value.pages[1].elements.some((element) => element.kind === 'shape' && element.shape === 'ellipse'))
  const source = await PDFDocument.create()
  source.addPage([600, 800]).drawText('LiftInk PDF source', { x: 80, y: 700 })
  const pdfBytes = await source.save()
  await page.locator('.editor-file-input').nth(1).setInputFiles({ name: 'source.pdf', mimeType: 'application/pdf', buffer: Buffer.from(pdfBytes) })
  await page.getByRole('dialog', { name: '插入 PDF' }).getByRole('button', { name: '插入 PDF' }).click()
  await waitDocument(noteId, (value) => Boolean(value.sourcePdfId))
  saved = (await page.evaluate((id) => window.liftInk.loadDocument(id), noteId)).value
  assert(saved.sourcePdfId?.endsWith('.pdf'), JSON.stringify({ pages: saved.pages.length, source: saved.sourcePdfId, status: await page.locator('.editor-save-state').textContent() }))
  assert.equal(saved.pages.length, 3)
  assert(saved.pages[2].backgroundAssetId)
  const pdfCanvas = page.getByLabel('笔记画布').nth(2)
  await pdfCanvas.scrollIntoViewIfNeeded()
  const pdfBox = await pdfCanvas.boundingBox()
  await page.getByRole('button', { name: '文本', exact: true }).click()
  await page.mouse.click(pdfBox.x + 160, pdfBox.y + 300)
  await page.getByLabel('文本内容').fill('PDF 批注')
  await page.getByRole('button', { name: '确定' }).click()
  await waitDocument(noteId, (value) => value.pages[2].elements.some((element) => element.kind === 'text'))
  await page.getByRole('button', { name: '选择', exact: true }).click()
  await pdfCanvas.getByText('PDF 批注').dblclick()
  await page.getByLabel('文本内容').fill('PDF 批注已改')
  await page.getByRole('button', { name: '确定' }).click()
  await waitDocument(noteId, (value) => value.pages[2].elements.some((element) => element.kind === 'text' && element.text === 'PDF 批注已改'))
  await page.getByRole('button', { name: '页面', exact: true }).click()
  await page.getByRole('button', { name: '第 3 页书签' }).click()
  await page.getByLabel('书签名称').fill('重点资料')
  await page.getByRole('button', { name: '确定' }).click()
  await page.getByRole('button', { name: '书签', exact: true }).click()
  assert(await page.getByRole('button', { name: '重点资料' }).isVisible())
  await pdfCanvas.scrollIntoViewIfNeeded()
  await page.screenshot({ path: 'screenshots/p1-p2-pdf-editor-1440x900.png', scale: 'css' })
  await page.getByRole('button', { name: '导出或备份' }).click()
  await page.getByRole('button', { name: '导出 PDF' }).click()
  await page.getByText(/已导出：/).waitFor({ timeout: 30000 })
  const exportedPdf = (await readdir(exportDir)).find((name) => name.endsWith('.pdf'))
  assert(exportedPdf)
  assert.equal((await PDFDocument.load(await readFile(join(exportDir, exportedPdf)))).getPageCount(), 3)
  await page.getByRole('button', { name: '导出或备份' }).click()
  await page.getByRole('button', { name: '导出 PNG' }).click()
  await page.getByText(/已导出：/).waitFor({ timeout: 30000 })
  const pngZipName = (await readdir(exportDir)).find((name) => name.endsWith('.zip'))
  assert(pngZipName)
  const pngZip = await JSZip.loadAsync(await readFile(join(exportDir, pngZipName)))
  assert.equal(Object.keys(pngZip.files).length, 3)
  await page.getByRole('button', { name: '导出或备份' }).click()
  await page.getByRole('button', { name: '原生备份' }).click()
  await page.getByText(/已导出：/).waitFor({ timeout: 30000 })
  const backup = (await readdir(exportDir)).find((name) => name.endsWith('.liftink'))
  assert(backup)
  const zip = await JSZip.loadAsync(await readFile(join(exportDir, backup)))
  const manifest = JSON.parse(await zip.file('manifest.json').async('string'))
  assert.equal(manifest.document.pages.length, 3)
  assert(zip.file(`assets/${saved.sourcePdfId}`))
  await page.getByRole('button', { name: '双开页面' }).click()
  await page.getByRole('button', { name: '摘录本页到当前页' }).click()
  await waitDocument(noteId, (value) => value.excerpts?.length === 1)
  const afterExcerpt = (await page.evaluate((id) => window.liftInk.loadDocument(id), noteId)).value
  assert.equal(afterExcerpt.excerpts?.length, 1)
  await page.screenshot({ path: 'screenshots/p1-p3-editor-1440x900.png', scale: 'css' })
  await page.getByRole('button', { name: '展开页面缩略图' }).click()
  await page.getByRole('button', { name: '页面', exact: true }).click()
  await page.getByRole('button', { name: '新增页面' }).click()
  await waitDocument(noteId, (value) => value.pages.length === 4)
  await page.getByRole('button', { name: '导出或备份' }).click()
  await page.getByRole('button', { name: '从 .liftink 恢复到当前笔记' }).click()
  await page.locator('.editor-file-input').nth(2).setInputFiles(join(exportDir, backup))
  const restored = await waitDocument(noteId, (value) => value.pages.length === 3 && !value.audioAssetId && !value.excerpts?.length)
  assert.equal(restored.sourcePdfId, saved.sourcePdfId)
  const source2 = await PDFDocument.create()
  source2.addPage([600, 800]).drawText('Second source', { x: 80, y: 700 })
  await page.locator('.editor-file-input').nth(1).setInputFiles({ name: 'second.pdf', mimeType: 'application/pdf', buffer: Buffer.from(await source2.save()) })
  await page.getByRole('dialog', { name: '插入 PDF' }).getByRole('button', { name: '插入 PDF' }).click()
  const multiSource = await waitDocument(noteId, (value) => value.pages.length === 4 && value.sourcePdfIds?.length === 2)
  assert.equal(multiSource.pages[3].sourcePageNumber, 1)
  await page.getByRole('button', { name: '导出或备份' }).click()
  await page.getByRole('button', { name: '原生备份' }).click()
  await page.getByText(/已导出：/).waitFor({ timeout: 30000 })
  const multiZip = await JSZip.loadAsync(await readFile(join(exportDir, backup)))
  for (const id of multiSource.sourcePdfIds) assert(multiZip.file(`assets/${id}`))
  const broken = new JSZip()
  broken.file('manifest.json', JSON.stringify({ format: 'liftink', version: 1, document: multiSource }))
  await page.locator('.editor-file-input').nth(2).setInputFiles({ name: 'broken.liftink', mimeType: 'application/zip', buffer: Buffer.from(await broken.generateAsync({ type: 'uint8array' })) })
  await page.getByText(/恢复失败：/).waitFor({ timeout: 5000 })
  const afterBroken = (await page.evaluate((id) => window.liftInk.loadDocument(id), noteId)).value
  assert.equal(afterBroken.revision, multiSource.revision, '损坏备份不应替换当前笔记')
  await page.getByRole('button', { name: '返回上一页' }).click()
  await page.getByRole('button', { name: '新建笔记' }).click()
  await page.getByRole('region', { name: '笔记页面' }).waitFor({ state: 'visible' })
  await page.getByLabel('笔记标题').fill('双开来源笔记')
  await page.keyboard.press('Control+s')
  await page.getByText('已保存', { exact: true }).waitFor()
  const secondId = await page.evaluate(async () => (await window.liftInk.loadNoteIndex()).value.find((entry) => entry.title === '双开来源笔记')?.id)
  assert(secondId)
  await page.getByRole('button', { name: '返回上一页' }).click()
  const search = page.getByRole('textbox', { name: '搜索笔记、PDF、关键词' })
  await search.fill('P1-P3 主笔记')
  await search.press('Enter')
  await page.getByRole('region', { name: '笔记页面' }).waitFor({ state: 'visible' })
  await page.getByRole('button', { name: '双开页面' }).click()
  await page.getByLabel('选择参照笔记').selectOption(secondId)
  await page.getByRole('complementary', { name: '双开笔记' }).getByLabel('笔记画布').waitFor({ state: 'visible' })
  await page.getByRole('button', { name: '摘录本页到当前页' }).click()
  const linked = await waitDocument(noteId, (value) => value.excerpts?.some((entry) => entry.sourceNoteId === secondId))
  assert(linked.excerpts.some((entry) => entry.sourceNoteId === secondId))
  await page.getByRole('button', { name: '关闭双开' }).click()
  await page.getByLabel('倒计时分钟').fill('1')
  await page.getByRole('button', { name: '开始倒计时' }).click()
  await page.getByRole('button', { name: '暂停倒计时' }).waitFor()
  assert((await stat(join(root, 'notes', `${noteId}.json`))).size > 0)
  console.log('P1-P3 editor flow passed: pages, lasso, layers, PDF import/export, portable restore, cross-note excerpt, tape, timer and audio sync')
} finally {
  await app.close()
  await rm(root, { recursive: true, force: true })
  await rm(exportDir, { recursive: true, force: true })
}
