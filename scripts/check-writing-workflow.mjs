import { strict as assert } from 'node:assert'
import { mkdtemp, readdir, rm } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { _electron as electron, expect } from '@playwright/test'

const root = await mkdtemp(join(tmpdir(), 'liftink-writing-workflow-'))
const launch = () => electron.launch({ args: ['.'], env: { ...process.env, LIFTINK_TEST_DATA_DIR: root } })
let app
try {
  app = await launch()
  const page = await app.firstWindow()
  await (await app.browserWindow(page)).evaluate((window) => window.setContentSize(1440, 900))
  const button = (name) => page.getByRole('button', { name, exact: true })
  const index = () => page.evaluate(async () => (await window.liftInk.loadNoteIndex()).value ?? [])
  const note = async (title) => (await index()).find((entry) => entry.title === title)
  const doc = async (id) => (await page.evaluate((id) => window.liftInk.loadDocument(id), id)).value
  const editor = page.getByRole('region', { name: '笔记页面', exact: true })
  const newNote = async (name) => {
    await page.getByRole('button', { name: '新建笔记' }).click()
    await editor.getByLabel('笔记标题').fill(name)
    await editor.getByText('未保存草稿').waitFor()
  }
  const stroke = async (canvas, y) => {
    const box = await canvas.boundingBox()
    assert(box)
    await page.mouse.move(box.x + box.width * 0.2, box.y + y)
    await page.mouse.down()
    await page.mouse.move(box.x + box.width * 0.5, box.y + y + 14, { steps: 8 })
    await page.mouse.up()
  }

  await newNote('不应保存的空白草稿')
  await button('返回上一页').click()
  assert.equal(await note('不应保存的空白草稿'), undefined)
  assert.equal(await readdir(join(root, 'notes')).then((names) => names.length, () => 0), 0)

  await newNote('左栏手写')
  const left = editor.getByLabel('笔记画布').first()
  await stroke(left, 120)
  await page.keyboard.press('Control+s')
  await expect.poll(() => note('左栏手写')).toMatchObject({ pageCount: 1, documentExpected: true })
  const leftNote = await note('左栏手写')
  assert(leftNote.updatedAt >= leftNote.createdAt && leftNote.createdAt > 0)
  const leftId = leftNote.id
  await expect.poll(async () => (await doc(leftId)).pages[0].elements.length).toBe(1)
  await editor.getByLabel('倒计时分钟').fill('1')
  await button('开始倒计时').click()
  await expect(button('暂停倒计时')).toBeEnabled()
  await page.waitForTimeout(1150)
  await button('暂停倒计时').click()
  await expect(button('重置倒计时')).toBeEnabled()
  await button('返回上一页').click()
  await button('查看专注时间统计').click()
  const focus = page.getByRole('region', { name: '专注时间统计' })
  await expect(focus.locator('.focus-ranking li').first()).toContainText('左栏手写')
  await expect.poll(async () => Object.values((await note('左栏手写')).focusByDay ?? {}).reduce((sum, ms) => sum + ms, 0)).toBeGreaterThan(1000)
  await button('返回首页').click()

  await newNote('右栏笔记')
  await page.keyboard.press('Control+s')
  await editor.getByText('已保存', { exact: true }).waitFor()
  await expect.poll(() => note('右栏笔记')).toMatchObject({ pageCount: 1 })
  const rightId = (await note('右栏笔记')).id
  await button('返回上一页').click()
  await page.locator('.note-card').filter({ hasText: '左栏手写' }).click()
  await button('双开页面').click()
  await page.getByLabel('选择参照笔记').selectOption(rightId)
  const right = page.getByRole('region', { name: '右侧笔记编辑器' })
  const rightCanvas = right.getByLabel('笔记画布')
  await rightCanvas.waitFor()
  const divider = page.getByRole('separator', { name: '调节双开比例' })
  const dividerBox = await divider.boundingBox()
  assert(dividerBox)
  await page.mouse.move(dividerBox.x + 3, dividerBox.y + 120)
  await page.mouse.down()
  await page.mouse.move(dividerBox.x - 90, dividerBox.y + 120, { steps: 6 })
  await page.mouse.up()
  await expect(divider).not.toHaveAttribute('aria-valuenow', '50')
  const viewport = (canvas) => canvas.locator('xpath=../..')
  await viewport(left).evaluate((element) => { element.scrollTop = 0 })
  await viewport(rightCanvas).evaluate((element) => { element.scrollTop = 0 })
  await stroke(rightCanvas, 110)
  await page.keyboard.press('Control+s')
  await expect.poll(async () => (await doc(rightId)).pages[0].elements.length).toBe(1)
  const leftPaper = await left.boundingBox()
  const rightPaper = await rightCanvas.boundingBox()
  assert(Math.abs(leftPaper.y - rightPaper.y) < 4, `双开纸面的起点应对齐：${leftPaper.y} / ${rightPaper.y}`)
  await page.screenshot({ path: 'screenshots/writing-dual-1440x900.png', scale: 'css' })
  assert.equal((await doc(leftId)).pages[0].elements.length, 1)
  await page.keyboard.press('Control+z')
  await expect.poll(async () => (await doc(rightId)).pages[0].elements.length).toBe(0)
  assert.equal((await doc(leftId)).pages[0].elements.length, 1)
  await button('关闭双开').click()
  await button('返回上一页').click()

  await button('标签').click()
  const tags = page.getByRole('region', { name: '标签页面' })
  await tags.getByRole('button', { name: /新建标签/ }).click()
  await tags.getByLabel('标签名称').fill('工作流验证')
  await button('保存标签').click()
  await button('重命名标签').click()
  await tags.getByLabel('标签名称').fill('回归测试标签')
  await button('保存标签').click()
  await expect(tags.getByRole('heading', { name: '回归测试标签' })).toBeVisible()
  await button('删除标签').click()
  await button('确认删除').click()
  await expect(tags.getByRole('heading', { name: '回归测试标签' })).toHaveCount(0)
  await button('常用文件').click()
  await expect(page.getByRole('region', { name: '常用文件列表' }).locator('.recent-file-row').first()).toBeVisible()
  await button('首页').click()

  await button('查看全部日程').click()
  const agenda = page.getByRole('region', { name: '日程详情页面' })
  await agenda.getByRole('button', { name: '新增目标' }).click()
  await page.getByLabel('目标名称').fill('完成两道题')
  await button('保存目标').click()
  await button('编辑目标 完成两道题').click()
  await page.getByLabel('目标名称').fill('完成三道题')
  await button('保存目标').click()
  await button('删除目标 完成三道题').click()
  await button('确认删除').click()
  await expect(agenda.getByText('完成三道题')).toHaveCount(0)
  await agenda.getByRole('button', { name: '新增日程' }).click()
  await expect(page.getByLabel('日程时间类型')).toHaveValue('all-day')
  await page.getByPlaceholder('输入日程内容').fill('全天复习')
  await button('添加日程').click()
  const agendaItem = agenda.getByText('全天复习', { exact: true })
  await expect(agendaItem).toBeVisible()
  const deleteAgendaItem = agenda.locator('.agenda-detail-item').filter({ hasText: '全天复习' }).getByRole('button', { name: '删除', exact: true })
  await deleteAgendaItem.click()
  await expect(page.getByRole('dialog', { name: '删除日程' })).toContainText('全天复习')
  await button('取消').click()
  await expect(agendaItem).toBeVisible()
  await deleteAgendaItem.click()
  await button('确认删除').click()
  await expect(agendaItem).toHaveCount(0)

  const stale = (await index()).map((entry) => entry.id === leftId || entry.id === rightId
    ? { ...entry, trashed: true, trashedAt: Date.now() - (entry.id === leftId ? 31 : 29) * 86400000 }
    : entry)
  await page.evaluate((records) => window.liftInk.saveNoteIndex(records), stale)
  assert.deepEqual(await page.evaluate(() => window.liftInk.sweepTrash()), [leftId])
  await page.evaluate((records) => window.liftInk.saveNoteIndex(records), stale)
  assert.equal(await doc(leftId), null)
  assert(await doc(rightId))
  await app.close()
  app = await launch()
  const reopened = await app.firstWindow()
  await reopened.getByRole('button', { name: '回收站', exact: true }).click()
  const trash = reopened.getByRole('region', { name: '回收站' })
  await expect(trash.getByText('右栏笔记')).toBeVisible()
  await expect(trash.getByText('左栏手写')).toHaveCount(0)
  console.log('Writing workflow passed: draft, timestamps, focus ranking, countdown, dual-pane write and undo, tags, favorites, goals, all-day events, confirmed deletion and 30-day trash')
} finally {
  await app?.close()
  await rm(root, { recursive: true, force: true })
}
