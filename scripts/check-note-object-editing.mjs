    await expect(image).toHaveAttribute('x', imageX)
    await page.keyboard.press('v')
    await expect(button('选择')).toHaveAttribute('aria-pressed', 'true')
    await drag(image)
    for (let i = 0; i < 3; i++) await button('缩小画布').click()
