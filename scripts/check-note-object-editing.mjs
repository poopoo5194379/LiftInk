    await page.keyboard.press('Control+s')
    await expect(page.getByText('已保存', { exact: true })).toBeVisible()
    await app.close()
    await launch()
    await page.getByText('重开对象测试', { exact: true }).first().click()
    const image = canvas().locator('image')
    await expect(image).toHaveAttribute('href', /^data:image\/png/)
    await expect(button('选择')).toHaveAttribute('aria-pressed', 'true')
    await drag(image)
    await expect(button('裁剪图片')).toBeEnabled()
