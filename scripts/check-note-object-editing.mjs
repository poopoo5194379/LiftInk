  const png = await makePng()
  await body.evaluate((element, png) => {
    const data = new DataTransfer()
    const bytes = Uint8Array.from(atob(png.split(',')[1]), (byte) => byte.charCodeAt(0))
    data.items.add(new File([bytes], 'clipboard-fixture.png', { type: 'image/png' }))
    element.dispatchEvent(new ClipboardEvent('paste', { clipboardData: data, bubbles: true, cancelable: true }))
  }, png)
  await expect(body.getByRole('img', { name: 'clipboard-fixture.png' })).toBeVisible({ timeout: 3000 })
