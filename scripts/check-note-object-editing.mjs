    const text = canvas().locator('text[data-text-id]')
    await expect(text).toHaveAttribute('fill', '#9d365c')
    await expect(text).toHaveAttribute('font-size', '34')
    await expect(canvas().nth(2).locator('image')).toHaveAttribute('href', /^data:image\/png/)
    await expect(canvas().nth(2).locator('tspan[fill="#245c83"]').first()).toHaveCSS('font-family', /Consolas/)
    const box = canvas().nth(2).locator('[data-text-box-hit]')
    await expect(box).toHaveAttribute('width', String(savedTextSize.width))
    await expect(box).toHaveAttribute('height', String(savedTextSize.height))
    await text.locator('tspan[fill="#245c83"]').first().dblclick()
    await expect(page.getByLabel('文本内容')).toHaveValue('**更新后的文本** *斜体* ~~划掉~~ `code`')
