import { strict as assert } from 'node:assert'
import { mkdtemp, readFile, realpath, rm } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { _electron as electron, expect } from '@playwright/test'
import JSZip from 'jszip'

const root = await mkdtemp(join(await realpath(tmpdir()), 'liftink-note-objects-'))
const executablePath = process.env.LIFTINK_TEST_PACKAGED_EXE
let app, page
let savedTextSize
const button = (name) => page.getByRole('button', { name, exact: true })
const canvas = () => page.getByLabel('笔记画布')
const launch = async () => {
  app = await electron.launch({ executablePath, args: executablePath ? [] : ['.'], env: { ...process.env, LIFTINK_TEST_DATA_DIR: root } })
  page = await app.firstWindow()
  page.setDefaultTimeout(5000)
  await (await app.browserWindow(page)).evaluate((window) => window.setContentSize(1440, 900))
}
const makePng = () => page.evaluate(() => {
  const canvas = document.createElement('canvas')
  canvas.width = 100
  canvas.height = 70
  canvas.getContext('2d').fillRect(0, 0, 100, 70)
  return canvas.toDataURL()
})
const drag = async (locator) => {
  await locator.scrollIntoViewIfNeeded()
  await locator.evaluate((element) => Promise.all(element.closest('main').getAnimations().map((animation) => animation.finished)))
  const before = Number(await locator.getAttribute('x'))
  const box = await locator.boundingBox()
  assert(box)
  const x = box.x + box.width * 0.5, y = box.y + box.height * 0.5
  assert(await locator.evaluate((element, [x, y]) => element.contains(document.elementFromPoint(x, y)), [x, y]),
    `Pointer target does not reach the ${await locator.evaluate((element) => element.tagName)} object`)
  await page.mouse.move(x, y)
  await page.mouse.down()
  await page.mouse.move(x + 55, y + 12, { steps: 8 })
  await page.mouse.up()
  await expect.poll(async () => Number(await locator.getAttribute('x')), { timeout: 2500 }).toBeGreaterThan(before + 15)
}

