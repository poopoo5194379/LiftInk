    assert.equal(narrow.height, sizeBefore.height)
    await resizeBox('调整文本框高度', 0, 28)
    const resized = await readSize()
    assert.equal(resized.width, narrow.width)
    assert(resized.height > narrow.height)
    assert(await text.locator(':scope > tspan').count() > linesBefore)
    await resizeBox('调整文本框宽高', 6, 10)
    savedTextSize = await readSize()
    assert(savedTextSize.width > resized.width && savedTextSize.height > resized.height)
    await expect(text).toHaveAttribute('font-size', '34')
    const blank = await boxHit.evaluate((element) => {
      const box = element.getBoundingClientRect()
      const x = box.left + box.width * 0.3, y = box.bottom - 3
      return document.elementFromPoint(x, y) === element ? { x, y } : null
    })
    assert(blank, 'The blank part of a text box must receive pointer input')
    const beforeY = Number(await text.getAttribute('y'))
    await page.mouse.move(blank.x, blank.y)
    await page.mouse.down()
    await page.mouse.move(blank.x - 6, blank.y + 7, { steps: 6 })
    await page.mouse.up()
    assert(Number(await text.getAttribute('y')) > beforeY + 15)
    assert.deepEqual(await readSize(), savedTextSize)

    const crossPage = async (object, target, x, y) => {
      const a = await object.boundingBox(), b = await target.boundingBox()
      assert(a && b)
      await page.mouse.move(a.x + a.width / 2, a.y + a.height / 2)
      await page.mouse.down()
      await page.mouse.move(b.x + x, b.y + y, { steps: 12 })
      await page.mouse.up()
    }
    await crossPage(text, canvas().nth(2), 55, 36)
    await expect(canvas().nth(2).locator('text[data-text-id]')).toHaveCount(1)
